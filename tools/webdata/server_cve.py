"""Refresh the bundled server-software CVE ranges (maintainers only; needs the network unless --from is given).

    python tools/webdata/server_cve.py                  # download every source
    python tools/webdata/server_cve.py --from DIR       # local copies: DIR/php-known-vulnerabilities.json,
                                                        #   DIR/apache-known-vulnerabilities.json,
                                                        #   DIR/security_advisories.xml (nginx), DIR/security-<n>.xml (Tomcat)

Writes ``vulnscan/data/web/server-cve.json``: product → CVEs with severity, affected version ranges (``at_or_above``
≤ v < ``below``) and the fixed versions, for WEB800 (spec §2.9). Sources:

* PHP and Apache httpd: ZAP's ``php-known-vulnerabilities.json`` / ``apache-known-vulnerabilities.json`` (pscanrules,
  Apache-2.0; generated by ZAP from the php-src security advisories and the httpd CVE records). Ranges ZAP marks
  ``assumed`` (versions older than every fixed branch, or "possibly affected") keep that flag: WEB800 is tentative there.
* nginx: the nginx.org security advisories (``xml/en/security_advisories.xml`` of nginx/nginx.org); "nginx/Windows"-only
  issues are skipped (the banner does not tell the platform).
* Apache Tomcat: the tomcat-site ``xdocs/security-<major>.xml`` pages ("Fixed in Apache Tomcat x.y.z" sections).
* OpenSSL and lighttpd: a short hand-maintained list (``MANUAL`` below) of high-impact issues from the vendors'
  advisories (facts; each entry names its advisory). OpenSSL banners are almost always distribution builds, which
  WEB800 reports as tentative anyway; the end-of-life check (WEB801, eol.json) is the main signal for them.

Severity mapping: ZAP's own; nginx major → high, medium → medium, minor/low → low; Tomcat Critical/Important/Moderate/Low
→ critical/high/medium/low.
"""

