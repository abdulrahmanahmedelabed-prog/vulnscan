def _get(url: str, timeout: float = 60.0) -> bytes:
    sys.path.insert(0, str(ROOT))
    from vulnscan import __version__
    req = urllib.request.Request(url, headers={"User-Agent": f"Kashif/{__version__} webdata-refresh"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:   # nosec - fixed maintainer URL
        return resp.read(16 * 1024 * 1024)


# ----------------------------------------------------------------------------------------------- versions

def version_key(v: str) -> tuple:
    """Order of server versions: numbers numerically, a letter suffix after a number is a later patch (OpenSSL
    ``1.0.1e`` > ``1.0.1``), alphabetic parts (Tomcat ``M1``/``RC1``, ``beta``) are pre-releases (``9.0.0.M1`` < ``9.0.0``)."""
    out = []
    for part in re.split(r"[.\-]", v.strip().lower()):
        if not part:
            continue
        m = re.match(r"^(\d+)([a-z]*)$", part)
        if m:
            out.append((2, int(m.group(1)), m.group(2), 0))
            continue
        m = re.match(r"^([a-z]+)(\d*)$", part)
        if m:
            out.append((0, 0, m.group(1), int(m.group(2) or 0)))
            continue
        out.append((1, 0, part, 0))
    return tuple(out)


# ----------------------------------------------------------------------------------------------- ZAP (PHP, httpd)

def from_zap(obj: dict) -> list[dict]:
    out = []
    for v in obj.get("vulnerabilities", []):
        cve = str(v.get("cve") or "")
        if not re.match(r"^CVE-\d{4}-\d{4,}$", cve):
            continue
        sev = str(v.get("severity", "")).lower()
        if sev not in ("critical", "high", "medium", "low"):
            continue
        ranges, fixed = [], []
        for a in v.get("affected", []):
            rng: dict = {"below": str(a.get("fixed") or NO_FIX)}
            intro = str(a.get("introduced") or "0")
            if intro not in ("0", ""):
                rng["at_or_above"] = intro
            if a.get("assumed"):
                rng["assumed"] = True
            ranges.append(rng)
            if a.get("fixed"):
                fixed.append(str(a["fixed"]))
        if not ranges:
            continue
        item = {"id": cve, "severity": sev, "ranges": ranges,
                "fixed": ", ".join(sorted(set(fixed), key=version_key)) or "none", "summary": str(v.get("name", ""))}
        if isinstance(v.get("cvss"), (int, float)):
            item["cvss"] = float(v["cvss"])
        out.append(item)
    return out


# ----------------------------------------------------------------------------------------------- nginx

_NGINX_SEV = {"major": "high", "medium": "medium", "minor": "low", "low": "low"}


def _next_patch(v: str) -> str:
    parts = v.split(".")
    parts[-1] = str(int(parts[-1]) + 1) if parts[-1].isdigit() else parts[-1]
    return ".".join(parts)


def from_nginx(xml: str) -> list[dict]:
    out = []
    for m in re.finditer(r"<item\b([^>]*)>", xml):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
        cves = [f"CVE-{c.strip()}" for c in attrs.get("cve", "").split(",") if c.strip()]
        sev = _NGINX_SEV.get(attrs.get("severity", "").lower())
        vuln = attrs.get("vulnerable", "")
        if not cves or sev is None or not vuln or vuln == "all" or "Windows" in vuln:
            continue
        goods = [g.strip().rstrip("+") for g in attrs.get("good", "").split(",") if g.strip().endswith("+")]
        ranges = []
        for part in vuln.split(","):
            part = part.strip()
            lo, _, hi = part.partition("-")
            hi = hi or lo
            if not re.match(r"^\d+(\.\d+)+$", lo) or not re.match(r"^\d+(\.\d+)+$", hi):
                continue
            branch = hi.rsplit(".", 1)[0]
            same = sorted((g for g in goods if g.rsplit(".", 1)[0] == branch and version_key(g) > version_key(hi)),
                          key=version_key)
            # a fixed release of an older branch inside lo..hi splits the span: "0.1.29-1.31.6" with good
            # "1.31.7+, 1.30.6+" means [0.1.29, 1.30.6) and [1.31.0, 1.31.7), not 1.30.6 as vulnerable
            start = lo
            for g in sorted((g for g in goods if version_key(lo) < version_key(g) <= version_key(hi)
                             and g.rsplit(".", 1)[0] != branch), key=version_key):
                if version_key(g) > version_key(start):
                    ranges.append({"at_or_above": start, "below": g})
                major, minor = g.split(".")[:2]
                start = f"{major}.{int(minor) + 1}.0"
            ranges.append({"at_or_above": start, "below": same[0] if same else _next_patch(hi)})
        if not ranges:
            continue
        summary = html.unescape(attrs.get("name", ""))
        for cve in cves:
            if re.match(r"^CVE-\d{4}-\d{4,}$", cve):
                out.append({"id": cve, "severity": sev, "ranges": [dict(r) for r in ranges],
                            "fixed": ", ".join(goods) or "none", "summary": summary})
    return out


# ----------------------------------------------------------------------------------------------- Tomcat

_TC_SEV = {"critical": "critical", "high": "high", "important": "high", "moderate": "medium", "low": "low"}


def from_tomcat(xml: str) -> list[dict]:
    out: dict[str, dict] = {}
    sections = re.split(r'<section name="Fixed in Apache Tomcat ', xml)[1:]
    for sec in sections:
        fixed = sec.split('"', 1)[0].strip()
        if not re.match(r"^\d+(\.\d+)+$", fixed):
            continue
        body = sec.split("</section>", 1)[0]
        entries = re.split(r"<p>\s*<strong>", body)[1:]
        for ent in entries:
            m = re.match(r"\s*(Critical|High|Important|Moderate|Low)\s*:\s*(.*?)</strong>", ent, re.S)
            cves = re.findall(r"<cve>(CVE-\d{4}-\d{4,})</cve>", ent)
            aff = re.search(r"Affects:\s*([^<]+)</p>", ent)
            if not m or not cves or not aff:
                continue
            sev = _TC_SEV[m.group(1).lower()]
            title = " ".join(html.unescape(re.sub(r"<[^>]+>", "", m.group(2))).split())
            ranges = []
            for part in aff.group(1).split(","):
                part = part.strip().rstrip("?").strip()
                rm = re.match(r"^(\d[\w.\-]*?)\s*(?:to|-)\s*(\d[\w.\-]*)$", part)
                lo = rm.group(1) if rm else (part if re.match(r"^\d[\w.\-]*$", part) else "")
                if not lo:
                    continue
                if re.split(r"[.\-]", lo)[:2] != fixed.split(".")[:2]:
                    continue          # another branch's range is listed in that branch's own section
                ranges.append({"at_or_above": lo, "below": fixed})
            if not ranges:
                continue
            for cve in cves:
                item = out.setdefault(cve, {"id": cve, "severity": sev, "ranges": [], "fixed": "", "summary": title})
                for r in ranges:
                    if r not in item["ranges"]:
                        item["ranges"].append(r)
                fx = [f for f in item["fixed"].split(", ") if f] + [fixed]
                item["fixed"] = ", ".join(sorted(set(fx), key=version_key))
    return list(out.values())


def from_manual(product: str) -> list[dict]:
    out = []
    for prod, cve, sev, ranges, summary in MANUAL:
        if prod != product:
            continue
        rs = []
        for lo, hi in ranges:
            r = {"below": hi}
            if lo:
                r["at_or_above"] = lo
            rs.append(r)
        out.append({"id": cve, "severity": sev, "ranges": rs, "fixed": ", ".join(hi for _lo, hi in ranges),
                    "summary": summary, "source": "manual"})
    return out


def build(sources: dict[str, object], day: str, notes: str = "") -> dict:
    products = {
        "php": from_zap(sources["php"]),                           # type: ignore[arg-type]
        "apache-http-server": from_zap(sources["apache"]),         # type: ignore[arg-type]
        "nginx": from_nginx(sources["nginx"]),                     # type: ignore[arg-type]
        "tomcat": [],
        "openssl": from_manual("openssl"),
        "lighttpd": from_manual("lighttpd"),
    }
    merged: dict[str, dict] = {}
    for xml in sources.get("tomcat", []):                          # type: ignore[union-attr]
        for item in from_tomcat(xml):
            cur = merged.get(item["id"])
            if cur is None:
                merged[item["id"]] = item
            else:
                for r in item["ranges"]:
                    if r not in cur["ranges"]:
                        cur["ranges"].append(r)
                fx = set(cur["fixed"].split(", ")) | set(item["fixed"].split(", "))
                cur["fixed"] = ", ".join(sorted((f for f in fx if f), key=version_key))
    products["tomcat"] = sorted(merged.values(), key=lambda x: x["id"], reverse=True)
    for name in ("php", "apache-http-server", "nginx"):
        if len(products[name]) < 10:
            raise SystemExit(f"suspiciously few {name} entries: {len(products[name])}")
    meta = {"schema_version": 1, "date": day, "source": SOURCE, "license": LICENSE,
            "generator": "tools/webdata/server_cve.py"}
    if notes:
        meta["notes"] = notes
    return {"meta": meta, "products": products}


def write(obj: dict, out_dir: Path = OUT_DIR) -> Path:
    sys.path.insert(0, str(ROOT))
    from vulnscan.webscan import data
    errors = data.validate_data(OUT_NAME, obj)
    if errors:
        raise SystemExit("schema errors: " + "; ".join(errors[:5]))
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / OUT_NAME
    path.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8", newline="\n")
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from", dest="src", help="directory with local copies of every source (see the module docstring)")
    ap.add_argument("--date", help="snapshot date YYYY-MM-DD (default: today, UTC)")
    ap.add_argument("--notes", default="", help="free-text provenance note stored in the header")
    ap.add_argument("--out", default=str(OUT_DIR), help="output directory (default: vulnscan/data/web)")
    args = ap.parse_args(argv)

    def load(local: str, url: str) -> bytes:
        return (Path(args.src) / local).read_bytes() if args.src else _get(url)

    sources: dict[str, object] = {
        "php": json.loads(load("php-known-vulnerabilities.json", ZAP.format(name="php-known-vulnerabilities.json"))),
        "apache": json.loads(load("apache-known-vulnerabilities.json",
                                  ZAP.format(name="apache-known-vulnerabilities.json"))),
        "nginx": load("security_advisories.xml", NGINX).decode("utf-8"),
        "tomcat": [load(f"security-{m}.xml", TOMCAT.format(major=m)).decode("utf-8") for m in TOMCAT_MAJORS],
    }
    day = args.date or datetime.now(timezone.utc).date().isoformat()
    obj = build(sources, day, args.notes)
    path = write(obj, Path(args.out))
    counts = ", ".join(f"{k} {len(v)}" for k, v in obj["products"].items())
    print(f"wrote {path} ({counts})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
