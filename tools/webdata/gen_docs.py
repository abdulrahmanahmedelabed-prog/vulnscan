"""Generate docs/web-checks.md from the rule registry and the remediation library (no network).

    python tools/webdata/gen_docs.py            # write docs/web-checks.md
    python tools/webdata/gen_docs.py --check    # exit 1 if the committed page is out of date

The page lists every passive web rule of ``vulnscan/webscan/rules.py`` (id, English and Arabic name, default severity
and allowed range, confidence, CWE, OWASP WSTG, ASVS 4.0.3, ASVS 5.0.0, remediation snippet ids) family by family, then
every remediation snippet of ``vulnscan/webscan/remediation.py`` with its caveat in English and Arabic. The output is
deterministic (no dates, placeholders shown as placeholders), so the check can run in CI.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "web-checks.md"

SEV_EN = {"critical": "Critical", "high": "High", "medium": "Medium", "low": "Low", "info": "Info"}
CONF_EN = {"certain": "certain", "firm": "firm", "tentative": "tentative"}
DOC_VALUES = {"expires": "<scan date + 6 months, e.g. 2027-05-13T00:00:00.000Z>"}


def _cell(text: str) -> str:
    return str(text).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def _anchor(sid: str) -> str:
    return sid.lower()


def _list(items) -> str:
    return ", ".join(items) if items else "—"


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from vulnscan.webscan import remediation
    from vulnscan.webscan.rules import FAMILIES, RULE_IDS, RULES, rules_for_family

    out: list[str] = []
    w = out.append
    w("# Kashif passive web checks")
    w("")
    w("<!-- Generated by tools/webdata/gen_docs.py from vulnscan/webscan/rules.py and vulnscan/webscan/remediation.py."
      " Do not edit by hand: run `python tools/webdata/gen_docs.py`. -->")
    w("")
    w(f"Every rule of the passive web scanner ({len(RULE_IDS)} rules), with its default severity and the range a "
      "finding may take, its default confidence, and its mappings to CWE, the OWASP Web Security Testing Guide (WSTG "
      "v4.2 checklist ids), OWASP ASVS 4.0.3 and OWASP ASVS 5.0.0 (\"—\" means no matching requirement). The mappings "
      "are Kashif's analyst mapping. The last column names the remediation snippets, listed after the tables.")
    w("")
    w("كل قواعد الفحص السلبي للمواقع، مع الخطورة الافتراضية ومداها، ودرجة الثقة، والربط بـ CWE وWSTG وASVS 4.0.3 "
      "وASVS 5.0.0، ومقتطفات الإصلاح لكل قاعدة.")
    w("")
    w("- **Severity:** critical, high, medium, low or info. A range means the rule sets the severity from context.")
    w("- **Confidence:** `certain` = deterministic protocol fact; `firm` = probably real; `tentative` = may exist, high "
      "false-positive chance. `--web-sensitivity strict` reports certain only, `default` certain and firm, `paranoid` "
      "everything, including the rules marked *paranoid only*.")
    w("- **Stability:** rule ids never change meaning and are never reused (1.x contract).")
    w("")
    w("## Contents")
    w("")
    for code, (en, ar) in FAMILIES.items():
        w(f"- [{code}. {en}](#family-{code.lower()}) · {ar}")
    w("- [Remediation snippets](#remediation-snippets) · مقتطفات الإصلاح")
    w("")
    for code, (en, ar) in FAMILIES.items():
        ids = rules_for_family(code)
        w(f'<a id="family-{code.lower()}"></a>')
        w("")
        w(f"## {code}. {en} · {ar}")
        w("")
        w("| Id | Check | الفحص | Severity | Confidence | CWE | WSTG | ASVS 4.0.3 | ASVS 5.0.0 | Fix |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for rid in ids:
            m = RULES[rid]
            sev = SEV_EN[m.severity]
            others = [SEV_EN[s] for s in m.allowed_severities if s != m.severity]
            if others:
                sev += " (" + ", ".join(others) + ")"
            conf = CONF_EN[m.confidence]
            oc = [c for c in m.allowed_confidences if c != m.confidence]
            if oc:
                conf += " (" + ", ".join(oc) + ")"
            name = m.name_en + (" *(paranoid only)*" if m.paranoid_only else "") + (" *(1.0)*" if m.existing else "")
            cwe = ", ".join([m.cwe, *m.cwe_variants]) if m.cwe else "—"
            fix = ", ".join(f"[{s}](#{_anchor(s)})" for s in m.fix) if m.fix else "—"
            w(f"| `{rid}` | {_cell(name)} | {_cell(m.name_ar)} | {sev} | {conf} | {cwe} | {_list(m.wstg)} | "
              f"{_list(m.asvs4)} | {_list(m.asvs5)} | {fix} |")
        w("")
    w("*(1.0)* marks rules that already existed in Kashif 1.0.x (same id and meaning).")
    w("")
    w("## Remediation snippets")
    w("")
    w("Reports show the platforms detected for the scanned site first (from the `Server` / `X-Powered-By` headers and "
      "the technology inventory) and the others collapsed, with `example.com` replaced by the scanned host. Every "
      "snippet passes Kashif's own header, CSP, HSTS and cookie checks.")
    w("")
    w("تعرض التقارير المنصات المكتشفة في الموقع أولًا ثم بقية المنصات مطوية، مع استبدال example.com باسم المضيف المفحوص.")
    w("")
    used: dict[str, list[str]] = {}
    for rid in RULE_IDS:
        for sid in RULES[rid].fix:
            used.setdefault(sid, []).append(rid)
    for sid, sn in remediation.SNIPPETS.items():
        w(f'<a id="{_anchor(sid)}"></a>')
        w("")
        body = remediation.to_markdown(sid, "en", heading="###", values=DOC_VALUES).rstrip("\n").split("\n")
        body[0] = f"### {sid} · {sn.title_en} · {sn.title_ar}"
        caveat_at = next(i for i, line in enumerate(body) if line.startswith("**Caution:**"))
        body.insert(caveat_at + 1, "")
        body.insert(caveat_at + 2, f"**تنبيه:** {sn.caveat_ar}")
        out.extend(body)
        w("")
        rules = used.get(sid, [])
        w("Used by: " + (", ".join(f"`{r}`" for r in rules) if rules else "—"))
        w("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="fail when docs/web-checks.md is out of date")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{args.out} is out of date: run python tools/webdata/gen_docs.py", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
