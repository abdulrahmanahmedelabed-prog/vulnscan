import sqlite3
from flask import Flask, request, session

app = Flask(__name__)


def get_db():
    return sqlite3.connect("app.db")


@app.post("/register")
def register():
    get_db().execute("INSERT INTO user (username, password) VALUES (?, ?)",
                     (request.form["username"], request.form["password"]))
    return "ok"


@app.post("/login")
def login():
    user = get_db().execute("SELECT * FROM user WHERE username = ?", (request.form["username"],)).fetchone()
    session["user_id"] = user["id"]          # primary key generated by the DB, never written by the user
    return "ok"


@app.post("/login2")
def login2():
    user = get_db().execute("SELECT * FROM user WHERE username = ?", (request.form["username"],)).fetchone()
    session["name"] = user["username"]       # user-written column: DF025 here is expected
    return "ok"
