# ----------------------------------------------------------------------------------------------- validator

_TYPES = {"object": dict, "array": list, "string": str, "integer": int, "number": (int, float), "boolean": bool,
          "null": type(None)}


def _is_type(value: Any, t: str) -> bool:
    if t in ("integer", "number") and isinstance(value, bool):
        return False
    return isinstance(value, _TYPES[t])


def validate(schema: dict, value: Any, path: str = "$") -> list[str]:
    """Errors of ``value`` against a JSON-Schema subset (type, enum, pattern, min/max, required, properties,
    additionalProperties, propertyNames, items, min/maxItems, min/maxProperties, minLength, anyOf)."""
    errs: list[str] = []
    if "anyOf" in schema:
        if all(validate(s, value, path) for s in schema["anyOf"]):
            errs.append(f"{path}: matches none of the allowed forms")
    t = schema.get("type")
    if t is not None:
        types = t if isinstance(t, list) else [t]
        if not any(_is_type(value, x) for x in types):
            return errs + [f"{path}: expected {'/'.join(types)}, got {type(value).__name__}"]
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{path}: {value!r} not one of {schema['enum']}")
    if isinstance(value, str):
        if "minLength" in schema and len(value) < schema["minLength"]:
            errs.append(f"{path}: shorter than {schema['minLength']}")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errs.append(f"{path}: {value[:80]!r} does not match {schema['pattern']}")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            errs.append(f"{path}: {value} < {schema['minimum']}")
        if "maximum" in schema and value > schema["maximum"]:
            errs.append(f"{path}: {value} > {schema['maximum']}")
    if isinstance(value, list):
        if "minItems" in schema and len(value) < schema["minItems"]:
            errs.append(f"{path}: fewer than {schema['minItems']} items")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            errs.append(f"{path}: more than {schema['maxItems']} items")
        if "items" in schema:
            for i, item in enumerate(value):
                errs += validate(schema["items"], item, f"{path}[{i}]")
    if isinstance(value, dict):
        for key in schema.get("required", ()):
            if key not in value:
                errs.append(f"{path}: missing {key!r}")
        if "minProperties" in schema and len(value) < schema["minProperties"]:
            errs.append(f"{path}: fewer than {schema['minProperties']} properties")
        props = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        names = schema.get("propertyNames")
        for key, item in value.items():
            if names is not None:
                errs += validate(names, key, f"{path}.<key {key!r}>")
            if key in props:
                errs += validate(props[key], item, f"{path}.{key}")
            elif extra is False:
                errs.append(f"{path}: unexpected key {key!r}")
            elif isinstance(extra, dict):
                errs += validate(extra, item, f"{path}.{key}")
    return errs


def validate_data(name: str, obj: Any) -> list[str]:
    """Errors of a parsed data file against its schema (unknown names are an error)."""
    schema = SCHEMAS.get(name)
    if schema is None:
        return [f"{name}: no schema"]
    errs = validate(schema, obj)
    meta = obj.get("meta") if isinstance(obj, dict) else None
    if isinstance(meta, dict) and meta.get("schema_version") not in (None, SCHEMA_VERSION):
        errs.append(f"{name}: schema_version {meta.get('schema_version')} != {SCHEMA_VERSION}")
    return errs


def validate_file(path: Path) -> list[str]:
    """Load ``path`` (``.json`` or ``.json.gz``) and validate it against the schema named by its file name."""
    try:
        obj = json.loads(_read(path).decode("utf-8"))
    except (OSError, ValueError) as e:
        return [f"{path.name}: unreadable ({e})"]
    return validate_data(path.name, obj)


# ----------------------------------------------------------------------------------------------- loading

_cache: dict[str, Any] = {}


def clear_cache() -> None:
    """Forget loaded files and the chosen user directory (tests, and after ``update-data``)."""
    _cache.clear()


def user_root() -> Path:
    home = os.environ.get("KASHIF_HOME") or os.environ.get("VULNSCAN_HOME")
    base = Path(home) if home else Path.home() / ".vulnscan"
    return base / "webdata"


def _read(path: Path) -> bytes:
    raw = path.read_bytes()
    if path.name.endswith(".gz"):
        with gzip.GzipFile(fileobj=io.BytesIO(raw)) as g:
            out = g.read(_DECOMPRESSED_CAP + 1)
        if len(out) > _DECOMPRESSED_CAP:
            raise ValueError(f"{path.name}: decompressed size above the cap")
        return out
    return raw


def _load_manifest(directory: Path) -> dict | None:
    p = directory / MANIFEST
    try:
        obj = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if validate(MANIFEST_SCHEMA, obj):
        return None
    return obj


def bundled_manifest() -> dict | None:
    if "manifest:bundled" not in _cache:
        _cache["manifest:bundled"] = _load_manifest(BUNDLED_DIR)
    return _cache["manifest:bundled"]


def _bundled_generated() -> str:
    man = bundled_manifest()
    if man:
        return man["generated"]
    dates = [d for d in (_file_meta_date(BUNDLED_DIR, n) for n in DATA_FILES) if d]
    return max(dates) if dates else "0000-00-00"


def user_dir() -> Path | None:
    """The newest installed user snapshot that is usable (same schema, newer than the bundled one), else None."""
    if "user_dir" in _cache:
        return _cache["user_dir"]
    chosen = None
    root = user_root()
    try:
        candidates = sorted((p for p in root.iterdir() if p.is_dir()), key=lambda p: p.name, reverse=True)
    except OSError:
        candidates = []
    floor = _bundled_generated()
    for d in candidates:
        man = _load_manifest(d)
        if man and man["schema_version"] == SCHEMA_VERSION and man["generated"] > floor:
            chosen = d
            break
    _cache["user_dir"] = chosen
    return chosen


def path_for(name: str) -> tuple[Path, str]:
    """``(path, origin)`` of a data file; origin is ``"user"`` for a verified updated copy, else ``"bundled"``."""
    d = user_dir()
    if d is not None:
        man = _load_manifest(d) or {}
        entry = man.get("files", {}).get(name)
        p = d / name
        if entry and p.is_file():
            key = f"verified:{p}"
            if key not in _cache:
                try:
                    _cache[key] = hashlib.sha256(p.read_bytes()).hexdigest() == entry["sha256"]
                except OSError:
                    _cache[key] = False
            if _cache[key]:
                return p, "user"
    return BUNDLED_DIR / name, "bundled"


def available(name: str) -> bool:
    return path_for(name)[0].is_file()


def load_bytes(name: str) -> bytes:
    """Raw content of a data file (gunzipped for ``.gz``). Raises ``FileNotFoundError`` when it is not bundled."""
    path, _origin = path_for(name)
    return _read(path)


def load_json(name: str) -> Any:
    """Parsed JSON of a data file (cached). A user copy that fails its schema falls back to the bundled one."""
    key = f"json:{name}"
    if key in _cache:
        return _cache[key]
    path, origin = path_for(name)
    obj = json.loads(_read(path).decode("utf-8"))
    if origin == "user" and name in SCHEMAS and validate_data(name, obj):
        obj = json.loads(_read(BUNDLED_DIR / name).decode("utf-8"))
    _cache[key] = obj
    return obj


def meta(name: str) -> dict:
    """The ``meta`` header of a data file (from its sidecar for non-JSON files); ``{}`` when unavailable."""
    try:
        if name in SIDECARS:
            return dict(load_json(SIDECARS[name]).get("meta", {}))
        obj = load_json(name)
    except (OSError, ValueError):
        return {}
    return dict(obj.get("meta", {})) if isinstance(obj, dict) else {}


def _file_meta_date(directory: Path, name: str) -> str | None:
    p = directory / SIDECARS.get(name, name)
    try:
        obj = json.loads(_read(p).decode("utf-8"))
    except (OSError, ValueError):
        return None
    m = obj.get("meta") if isinstance(obj, dict) else None
    d = m.get("date") if isinstance(m, dict) else None
    return d if isinstance(d, str) and re.match(_DATE, d) else None


def file_date(name: str) -> date | None:
    d = meta(name).get("date")
    try:
        return date.fromisoformat(d) if d else None
    except ValueError:
        return None


def snapshot_date(names: tuple[str, ...] | None = None) -> date | None:
    """The oldest date among the available data files ("web data as of <date>")."""
    dates = [d for d in (file_date(n) for n in (names or DATA_FILES) if available(n)) if d]
    return min(dates) if dates else None


def as_of(lang: str = "en") -> str:
    d = snapshot_date()
    if d is None:
        return "لا توجد بيانات ويب مضمّنة" if lang == "ar" else "no bundled web data"
    return f"بيانات الويب بتاريخ {d.isoformat()}" if lang == "ar" else f"web data as of {d.isoformat()}"


_DAYS_AR = ("يوم واحد", "يومين", "{n} أيام", "{n} يومًا", "{n} يوم")   # same forms as rules.PLURAL_PARAMS["days"]


def staleness(now: datetime | None = None) -> list[dict]:
    """Staleness notes (§4.4 step 3): ``[{code, en, ar, rules}]``. ``rules`` is non-empty for the WEB991 note."""
    from ..i18n.plural import ar_count   # lazy: vulnscan.i18n may import webscan modules
    today = (now or datetime.now(timezone.utc)).date()
    out: list[dict] = []
    oldest = snapshot_date()
    if oldest is not None:
        age = (today - oldest).days
        if age > STALE_NOTE_DAYS:
            en_days = f"{age} day" if age == 1 else f"{age} days"
            out.append({"code": "data_old", "rules": (),
                        "en": _STALE_EN.format(days=en_days, date=oldest.isoformat()),
                        "ar": _STALE_AR.format(days=ar_count(age, _DAYS_AR), date=oldest.isoformat())})
    for name, rules in VULN_DATA.items():
        d = file_date(name) if available(name) else None
        if d is not None and (today - d).days > STALE_VULN_DAYS:
            out.append({"code": "vuln_data_old", "rules": rules, "file": name,
                        "en": _VULN_EN, "ar": _VULN_AR})
    return out


_STALE_EN = "Web data was last updated {days} ago (as of {date}); run kashif update-data --web."
_STALE_AR = "آخر تحديث لبيانات الويب كان قبل {days} (بتاريخ {date})؛ شغّل kashif update-data --web."
_VULN_EN = "Vulnerability data is old; results may miss recent CVEs."
_VULN_AR = "بيانات الثغرات قديمة؛ قد تفوت النتائج ثغرات حديثة."


def i18n_catalog() -> tuple[dict[str, str], list[tuple[str, str]]]:
    """``(CATALOG, PATTERNS)`` for the Arabic texts this module emits (``as_of``, ``staleness``), for cat_web2."""
    from .rules import template_patterns
    catalog = {_VULN_AR: _VULN_EN, "لا توجد بيانات ويب مضمّنة": "no bundled web data"}
    patterns = [(r"بيانات الويب بتاريخ (?P<date>\d{4}-\d{2}-\d{2})", r"web data as of \g<date>")]
    patterns += template_patterns(_STALE_AR, _STALE_EN)
    return catalog, patterns


