"""Loader for the bundled web data snapshots (``vulnscan/data/web/``), their JSON schemas and staleness (spec §4.4).

Every JSON data file is an object with a ``"meta"`` header (``schema_version``, ``date``, ``source``, ``license``) and
file-specific keys described in :data:`SCHEMAS`. The Public Suffix List is kept unmodified (``psl.dat.gz``, MPL-2.0)
with its header in the sidecar ``psl.dat.meta.json``. ``MANIFEST.json`` (name, date, source, licence, sha256 of every
file) is generated by ``tools/webdata/validate.py`` (WP17); this loader reads it but never needs it.

User-side updates (``kashif update-data --web``, WP17) unpack into ``<home>/webdata/<date>/`` where ``<home>`` is
``$KASHIF_HOME``, else ``$VULNSCAN_HOME``, else ``~/.vulnscan``. Such a directory is preferred when its manifest has the
same schema version and is newer than the bundled one, and only for files whose sha256 matches that manifest;
anything else falls back to the bundled snapshot, so ``--offline`` always works.

Loading is lazy and cached; nothing here touches the network.
"""

