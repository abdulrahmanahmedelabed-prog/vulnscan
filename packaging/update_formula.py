"""Write Formula/kashif.rb (the Homebrew formula) for a release, from that release's SHA256SUMS.txt.

Usage:
    python packaging/update_formula.py v0.8.0 path/to/SHA256SUMS.txt

The release workflow runs this after publishing, so `brew upgrade kashif` always gets the latest release. Homebrew
downloads the binary with curl, which sets no quarantine attribute, so macOS Gatekeeper does not block the
un-notarized binary the way it blocks a file downloaded by a browser.
"""

from __future__ import annotations

import pathlib
import re
import sys

REPO = "abdulrahmanahmedelabed-prog/vulnscan"
FORMULA = pathlib.Path(__file__).resolve().parent.parent / "Formula" / "kashif.rb"
# The release asset per platform: the kashif-* name, or for a release made before the rename (which has only the
# byte-identical legacy copy) the vulnscan-* name.
ASSETS = {"macos_arm64": ("kashif-macos-arm64", "vulnscan-macos-arm64"),
          "macos_x86_64": ("kashif-macos-x86_64", "vulnscan-macos-x86_64"),
          "linux_x86_64": ("kashif-linux-x86_64", "vulnscan-linux")}

TEMPLATE = '''# Homebrew formula for Kashif (vulnscan). Generated by packaging/update_formula.py at each release; do not edit.
#   brew tap kashif/vulnscan https://github.com/{repo}
#   brew install kashif
class Kashif < Formula
  desc "Zero-dependency SAST with inter-procedural dataflow analysis for 12 languages"
  homepage "https://abdulrahmanahmedelabed-prog.github.io/vulnscan/"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/{repo}/releases/download/v{version}/{macos_arm64}"
      sha256 "{macos_arm64_sha256}"
    end
    on_intel do
      url "https://github.com/{repo}/releases/download/v{version}/{macos_x86_64}"
      sha256 "{macos_x86_64_sha256}"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/{repo}/releases/download/v{version}/{linux_x86_64}"
      sha256 "{linux_x86_64_sha256}"
    end
  end

  def install
    binary = Dir["kashif-*", "vulnscan-*"].first
    odie "release binary not found" if binary.nil?
    bin.install binary => "kashif"
    # the pre-rename command name, kept as an alias
    bin.install_symlink "kashif" => "vulnscan"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/kashif --version")
    assert_match version.to_s, shell_output("#{{bin}}/vulnscan --version")
  end
end
'''


def render(tag: str, sums_text: str) -> str:
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise SystemExit(f"bad tag: {tag!r}")
    sums = {}
    for line in sums_text.splitlines():
        m = re.fullmatch(r"([0-9a-f]{64})\s+\*?(\S+)", line.strip())
        if m:
            sums[m.group(2)] = m.group(1)
    values = {"repo": REPO, "version": tag[1:]}
    missing = []
    for key, names in ASSETS.items():
        name = next((n for n in names if n in sums), None)
        if name is None:
            missing.append(names[0])
            continue
        values[key], values[key + "_sha256"] = name, sums[name]
    if missing:
        raise SystemExit(f"SHA256SUMS.txt lacks: {', '.join(missing)}")
    out = TEMPLATE
    for k, v in values.items():
        out = out.replace("{" + k + "}", v)
    return out.replace("{{", "{").replace("}}", "}")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    FORMULA.parent.mkdir(exist_ok=True)
    FORMULA.write_text(render(argv[0], pathlib.Path(argv[1]).read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {FORMULA}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
